import assert from 'node:assert/strict';
import * as T from '../../../app/vendor/three-0.180.0/three.module.min.js';
import {attachmentAt} from '../../../tools/hand-ground/mounted.js';
const scene=new T.Scene(),group=new T.Group();scene.add(group);
const material=new T.MeshLambertMaterial(),wall=new T.Mesh(new T.BoxGeometry(1,0.86,4).translate(0,0.43,0),material);group.add(wall);
const post=new T.InstancedMesh(new T.BoxGeometry(0.09,0.62,0.09),material,1);group.add(post);scene.updateMatrixWorld(true);
const matrix=new T.Matrix4().makeTranslation(0,1.15,0),D={THREE:T};let result=attachmentAt(D,post,matrix);
assert.ok(result);assert.ok(Math.abs(result.contacts[0].gap+0.02)<1e-5);assert.equal(result.onPaving,false);
assert.equal(attachmentAt(D,post,new T.Matrix4().makeTranslation(0,2,0)),null);
wall.visible=false;assert.equal(attachmentAt(D,post,matrix),null);wall.visible=true;
wall.material=new T.MeshLambertMaterial({transparent:true});assert.equal(attachmentAt(D,post,matrix),null);wall.material=material;
const paving=new T.Mesh(new T.BoxGeometry(4,0.1,4).translate(0,0.81,0),material);paving.geometry.setAttribute('ruv',new T.Float32BufferAttribute(new Float32Array(paving.geometry.attributes.position.count*2),2));group.add(paving);scene.updateMatrixWorld(true);
assert.equal(attachmentAt(D,post,matrix).onPaving,true);
const lower=new T.Matrix4().makeTranslation(0,1,0);
assert.equal(attachmentAt(D,post,lower)?.onPaving,undefined,'No false support through a wall top');
wall.geometry=new T.BoxGeometry(1,0.6,4).translate(0,0.3,0);
assert.equal(attachmentAt(D,post,lower).onPaving,true,'A buried base still obstructs paving above it');
wall.geometry=new T.BoxGeometry(1,0.86,4).translate(0,0.43,0);
group.remove(paving);const foot=new T.InstancedMesh(new T.BoxGeometry(0.22,7.4,0.22).translate(0,3.7,0),material,1);group.add(foot);scene.updateMatrixWorld(true);
assert.ok(attachmentAt(D,foot,new T.Matrix4().makeTranslation(0.6,1,0)),'Base corner contact at a slab edge must count');
console.log('PASS: actual base contact, unsupported/hidden/transparent rejection, paving stays an obstruction, slab-edge contact');
