"""Build the static web version of Just Watts into dist-web/ (deploy that folder, e.g. on Vercel).

    python web/build.py [--out dist-web]

Same app/ sources as the local app; the build only switches js/mode.js to 'web', drops the
server-only pages and adds vercel.json (static, SPA fallback, security headers). No Node or
bundler needed. Minimal on purpose: Web Bluetooth, the in-page ride engine, IndexedDB history and
the built-in coach; uploads and agents stay in the local app.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
WEB = ROOT / "web"
SERVER_ONLY = {"connect.html", "js/package.json"}


def build(out: Path) -> dict:
    if out.exists():  # keep the Vercel project link (.vercel) so deploys from out/ stay on one project
        for child in out.iterdir():
            if child.name != ".vercel":
                shutil.rmtree(child) if child.is_dir() else child.unlink()
    files = []
    for src in sorted(APP.rglob("*")):
        rel = src.relative_to(APP).as_posix()
        if src.is_dir() or rel in SERVER_ONLY:
            continue
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        files.append(rel)
    (out / "js" / "mode.js").write_text("// generated by web/build.py\nexport const MODE = 'web';\n", encoding="utf-8")
    digest = hashlib.sha256()
    for rel in files:
        digest.update(rel.encode())
        digest.update((out / rel).read_bytes())
    shutil.copy2(WEB / "vercel.json", out / "vercel.json")
    # serverless functions: the Strava token relay and the accounts/sync/community API (shared code in api/_lib)
    shutil.copytree(WEB / "api", out / "api", ignore=shutil.ignore_patterns("node_modules"))
    for name in ("package.json", "package-lock.json"):  # Vercel installs the functions' one dependency from these
        shutil.copy2(WEB / name, out / name)
    return {"out": str(out), "version": digest.hexdigest()[:12], "files": len(files) + 1}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(ROOT / "dist-web"))
    info = build(Path(ap.parse_args(argv).out))
    print(json.dumps(info))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
